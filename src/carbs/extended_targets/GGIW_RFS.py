    def _correct_prob_density(self, timestep, parted_meas, probDensity, filt_args):
        # means = []
        # covariances = []

        if parted_meas:

            weights = []

            Mix_temp = GGIWMixture()

            det_weights = [self.prob_detection * x for x in probDensity.weights]

            for z in parted_meas: 

                w_lst = []

                # Convert the measurement set from list of len N of Dx1 arrays to 
                # an DxN array 
                num_meas = len(z)
                meas_d = z[0].shape[0]
                z_array = np.array(z).reshape((num_meas, meas_d)).transpose()

                for jj in range(0, len(probDensity)):
                    cur_dist = probDensity[jj] 
                    (upd_dist, qz) = self.filter.correct(timestep, z_array, cur_dist, **filt_args) 
                    w = qz * det_weights[jj]

                    Mix_temp.add_components(upd_dist.alpha, upd_dist.beta, upd_dist.mean, upd_dist.covariance, upd_dist.IWdof, upd_dist.IWshape, w)            

                    w_lst.append(w)

                weights.extend(
                    [x / (self.clutter_rate * self.clutter_den + sum(w_lst)) for x in w_lst]
                )

            Mix_temp.weights = weights

            return Mix_temp
        else:
            return probDensity

    def _prune(self):
        """Removes hypotheses below a threshold.

        This should be called once per time step after the correction and
        before the state extraction.
        """
        inds = np.where(np.asarray(self._Mixture.weights) < self.prune_threshold)[0]
        self._Mixture.remove_components(inds.flatten().tolist())
        return inds

    def _merge(self):
            """Merges nearby hypotheses."""
            loop_inds = set(range(0, len(self._Mixture.means)))

            w_lst = []
            a_lst = []
            b_lst = []
            m_lst = []
            p_lst = []
            v_lst = []
            V_lst = []
            while len(loop_inds) > 0:
                jj = int(np.argmax(self._Mixture.weights))
                comp_inds = []
                inv_cov = la.inv(self._Mixture.covariances[jj])
                for ii in loop_inds:
                    diff = self._Mixture.means[ii] - self._Mixture.means[jj]
                    val = diff.T @ inv_cov @ diff
                    if val <= self.merge_threshold:
                        comp_inds.append(ii)
                w_new = sum([self._Mixture.weights[ii] for ii in comp_inds])
                m_new = (
                    sum(
                        [
                            self._Mixture.weights[ii] * self._Mixture.means[ii]
                            for ii in comp_inds
                        ]
                    )
                    / w_new
                )
                p_new = (
                    sum(
                        [
                            self._Mixture.weights[ii] * self._Mixture.covariances[ii]
                            for ii in comp_inds
                        ]
                    )
                    / w_new
                )
                p_new = 0.5 * (p_new+p_new.T)
                a_new = (
                    sum(
                        [
                            self._Mixture.weights[ii] * self._Mixture.alphas[ii]
                            for ii in comp_inds
                        ]
                    )
                    / w_new
                )
                b_new = (
                    sum(
                        [
                            self._Mixture.weights[ii] * self._Mixture.betas[ii]
                            for ii in comp_inds
                        ]
                    )
                    / w_new
                )
                v_new = (
                    sum(
                        [
                            self._Mixture.weights[ii] * self._Mixture.IWdofs[ii]
                            for ii in comp_inds
                        ]
                    )
                    / w_new
                )
                V_new = (
                    sum(
                        [
                            self._Mixture.weights[ii] * self._Mixture.IWshapes[ii]
                            for ii in comp_inds
                        ]
                    )
                    / w_new
                )

                w_lst.append(w_new)
                m_lst.append(m_new)
                p_lst.append(p_new)
                a_lst.append(a_new)
                b_lst.append(b_new)
                v_lst.append(v_new)
                V_lst.append(V_new)

                loop_inds = loop_inds.symmetric_difference(comp_inds)
                for ii in comp_inds:
                    self._Mixture.weights[ii] = -1
            # self._Mixture = smodels.GaussianMixture(
            #     means=m_lst, covariances=p_lst, weights=w_lst
            # )

            self._Mixture = GGIWMixture(alphas=a_lst,betas=b_lst,means=m_lst,covariances=p_lst,IWdofs=v_lst,IWshapes=V_lst)
            self._Mixture.weights = w_lst



    def _cap(self):
        """Removes least likely hypotheses until a maximum number is reached.

        This should be called once per time step after pruning and
        before the state extraction.
        """
        if len(self._Mixture.weights) > self.max_terms:
            idx = np.argsort(self._Mixture.weights)
            w = sum(self._Mixture.weights)
            self._Mixture.remove_components(idx[0 : -self.max_terms])
            self._Mixture.weights = [
                x * (w / sum(self._Mixture.weights)) for x in self._Mixture.weights
            ]
            return idx[0 : -self.max_terms].tolist()
        return []

    def extract_states(self):
        """Extracts the best state estimates.

        This extracts the best states from the distribution. It should be
        called once per time step after the correction function.
        """
        inds = np.where(np.asarray(self._Mixture.weights) >= self.extract_threshold)
        inds = np.ndarray.flatten(inds[0])
        s_lst = []
        c_lst = []
        for jj in inds:
            jj = int(jj)
            num_reps = round(self._Mixture.weights[jj])
            s_lst.extend([self._Mixture.means[jj]] * num_reps)
            if self.save_covs:
                c_lst.extend([self._Mixture.covariances[jj]] * num_reps)
        self._states.append(s_lst)
        if self.save_covs:
            self._covs.append(c_lst)

    def extract_mixture(self): 
        inds = np.where(np.asarray(self._Mixture.weights) >= self.extract_threshold)[0]

        temp = GGIWMixture() 

        for ii in inds:
            mix = self._Mixture[int(ii)]
            temp.add_components(
                mix.alpha,
                mix.beta,
                mix.mean,
                mix.covariance,
                mix.IWdof,
                mix.IWshape,
                self._Mixture.weights[ii]
            )

        return temp

    def cleanup(
        self,
        enable_prune=True,
        enable_cap=True,
        enable_merge=True,
        enable_extract=True,
        extract_kwargs=None,
    ):
        """Performs the cleanup step of the filter.

        This can prune, cap, and extract states. It must be called once per
        timestep. If this is called with `enable_extract` set to true then
        the extract states method does not need to be called separately. It is
        recommended to call this function instead of
        :meth:`carbs.swarm_estimator.tracker.GeneralizedLabeledMultiBernoulli.extract_states`
        directly.

        Parameters
        ----------
        enable_prune : bool, optional
            Flag indicating if prunning should be performed. The default is True.
        enable_cap : bool, optional
            Flag indicating if capping should be performed. The default is True.
        enable_merge : bool, optional
            Flag indicating if merging should be performed. The default is True.
        enable_extract : bool, optional
            Flag indicating if state extraction should be performed. The default is True.
        extract_kwargs : dict, optional
            Extra arguments to pass to the extract function.
        """
        if enable_prune:
            self._prune()
        if enable_merge:
            self._merge()
        if enable_cap:
            self._cap()
        if enable_extract:
            if extract_kwargs is None:
                extract_kwargs = {}
            self.extract_states(**extract_kwargs)

