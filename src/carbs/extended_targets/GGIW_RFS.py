    def _prune(self):
        """Removes hypotheses below a threshold.

        This should be called once per time step after the correction and
        before the state extraction.
        """
        inds = np.where(np.asarray(self._Mixture.weights) < self.prune_threshold)[0]
        self._Mixture.remove_components(inds.flatten().tolist())
        return inds

    def _merge(self):
            """Merges nearby hypotheses."""
            loop_inds = set(range(len(self._Mixture.means)))
            if len(loop_inds) < 2:
                # Exit if num component is less than 2
                return

            if self.merge_as_average:
                loop_inds = set(range(len(self._Mixture.means)))
                
                w_lst = []
                a_lst = []
                b_lst = []
                m_lst = []
                p_lst = []
                v_lst = []
                V_lst = []
                
                while loop_inds:
                    remaining_weights = {i: self._Mixture.weights[i] for i in loop_inds}
                    jj = max(remaining_weights, key=remaining_weights.get)
                    
                    comp_inds = set()
                    inv_cov = la.inv(self._Mixture.covariances[jj])
                    
                    for ii in loop_inds:
                        diff = self._Mixture.means[ii] - self._Mixture.means[jj]
                        val = diff.T @ inv_cov @ diff
                        if val <= self.merge_threshold:
                            comp_inds.add(ii)
                    
                    w_new = sum([self._Mixture.weights[ii] for ii in comp_inds])
                    
                    if w_new <= 0:
                        loop_inds = loop_inds.difference(comp_inds)
                        continue
                        
                    m_new = sum([self._Mixture.weights[ii] * self._Mixture.means[ii] for ii in comp_inds]) / w_new
                    
                    p_new = sum([self._Mixture.weights[ii] * self._Mixture.covariances[ii] for ii in comp_inds]) / w_new
                    p_new = 0.5 * (p_new + p_new.T) 
                    
                    a_new = sum([self._Mixture.weights[ii] * self._Mixture.alphas[ii] for ii in comp_inds]) / w_new
                    
                    b_new = sum([self._Mixture.weights[ii] * self._Mixture.betas[ii] for ii in comp_inds]) / w_new
                    
                    v_new = sum([self._Mixture.weights[ii] * self._Mixture.IWdofs[ii] for ii in comp_inds]) / w_new
                    
                    V_new = sum([self._Mixture.weights[ii] * self._Mixture.IWshapes[ii] for ii in comp_inds]) / w_new
                    
                    w_lst.append(w_new)
                    m_lst.append(m_new)
                    p_lst.append(p_new)
                    a_lst.append(a_new)
                    b_lst.append(b_new)
                    v_lst.append(v_new)
                    V_lst.append(V_new)
                    
                    loop_inds = loop_inds.difference(comp_inds)
                
                self._Mixture = GGIWMixture(
                    alphas=a_lst,
                    betas=b_lst,
                    means=m_lst,
                    covariances=p_lst,
                    IWdofs=v_lst,
                    IWshapes=V_lst,
                    weights=w_lst
                )
            else:
                loop_inds = set(range(len(self._Mixture.means)))
                
                new_mixture = GGIWMixture()

                # Calculate the KL difference matrix of component distribution
                gauss_dist = gauss_KL_diff(self._Mixture.means, self._Mixture.covariances)
                iw_dist = iw_KL_diff(self._Mixture.IWdofs, self._Mixture.IWshapes)
                gamma_dist = gamma_KL_diff(self._Mixture.alphas, self._Mixture.betas)

                tot_dist = gauss_dist + iw_dist + gamma_dist
                
                while len(loop_inds) > 0:
                    jj = int(np.argmax(self._Mixture.weights))

                    comp_ind = []
                    for ii in loop_inds:
                        if tot_dist[jj,ii] <= self.merge_threshold:
                            comp_ind.append(ii)
                    cluster_weight = [self._Mixture.weights[ii] for ii in comp_ind]
                    cluster_mean =  [self._Mixture.means[ii] for ii in comp_ind]
                    cluster_cov =  [self._Mixture.covariances[ii] for ii in comp_ind]
                    cluster_alpha =  [self._Mixture.alphas[ii] for ii in comp_ind]
                    cluster_beta =  [self._Mixture.betas[ii] for ii in comp_ind]
                    cluster_iwdof =  [self._Mixture.IWdofs[ii] for ii in comp_ind]
                    cluster_iwshape = [self._Mixture.IWshapes[ii] for ii in comp_ind]

                    w_merged, ggiw_merged = ggiw_merge(w=cluster_weight, means=cluster_mean, \
                                                    covs = cluster_cov, alphas= cluster_alpha, \
                                                        betas = cluster_beta, IWdof=cluster_iwdof, \
                                                            IWshape=cluster_iwshape, opt_alpha=True, opt_nu=True)
                    new_mixture.add_components(weights=w_merged, ggiw=ggiw_merged)
                    
                    loop_inds = loop_inds.symmetric_difference(comp_ind)
                    for ii in comp_ind:
                        self._Mixture.weights[ii] = -1
                
                self._Mixture = new_mixture

    def _cap(self):
        """Removes least likely hypotheses until a maximum number is reached.

        This should be called once per time step after pruning and
        before the state extraction.
        """
        if len(self._Mixture.weights) > self.max_terms:
            idx = np.argsort(self._Mixture.weights)
            w = sum(self._Mixture.weights)
            self._Mixture.remove_components(idx[0 : -self.max_terms])
            self._Mixture.weights = [
                x * (w / sum(self._Mixture.weights)) for x in self._Mixture.weights
            ]
            return idx[0 : -self.max_terms].tolist()

    def extract_states(self):
        """Extracts the best state estimates.

        This extracts the best states from the distribution. It should be
        called once per time step after the correction function.
        """
        inds = np.where(np.asarray(self._Mixture.weights) >= self.extract_threshold)
        inds = np.ndarray.flatten(inds[0])
        s_lst = []
        c_lst = []
        for jj in inds:
            jj = int(jj)
            num_reps = round(self._Mixture.weights[jj])
            s_lst.extend([self._Mixture.means[jj]] * num_reps)
            if self.save_covs:
                c_lst.extend([self._Mixture.covariances[jj]] * num_reps)
        self._states.append(s_lst)
        if self.save_covs:
            self._covs.append(c_lst)

    def extract_mixture(self): 
        inds = np.where(np.asarray(self._Mixture.weights) >= self.extract_threshold)[0]

        temp = GGIWMixture() 

        for ii in inds:
            mix = self._Mixture[int(ii)]
            temp.add_components(
                mix.alpha,
                mix.beta,
                mix.mean,
                mix.covariance,
                mix.IWdof,
                mix.IWshape,
                self._Mixture.weights[ii]
            )

        self.extracted_mixture.append(temp)

        return temp

    def cleanup(
        self,
        enable_prune=True,
        enable_cap=True,
        enable_merge=True,
        enable_extract=True,
        extract_kwargs=None,
    ):
        """Performs the cleanup step of the filter.

        This can prune, cap, and extract states. It must be called once per
        timestep. If this is called with `enable_extract` set to true then
        the extract states method does not need to be called separately. It is
        recommended to call this function instead of
        :meth:`carbs.swarm_estimator.tracker.GeneralizedLabeledMultiBernoulli.extract_states`
        directly.

        Parameters
        ----------
        enable_prune : bool, optional
            Flag indicating if prunning should be performed. The default is True.
        enable_cap : bool, optional
            Flag indicating if capping should be performed. The default is True.
        enable_merge : bool, optional
            Flag indicating if merging should be performed. The default is True.
        enable_extract : bool, optional
            Flag indicating if state extraction should be performed. The default is True.
        extract_kwargs : dict, optional
            Extra arguments to pass to the extract function.
        """
        if enable_prune:
            self._prune()
        if enable_merge:
            self._merge()
        if enable_cap:
            self._cap()
        if enable_extract:
            if extract_kwargs is None:
                extract_kwargs = {}
            self.extract_states(**extract_kwargs)
            self.extract_mixture(**extract_kwargs)

